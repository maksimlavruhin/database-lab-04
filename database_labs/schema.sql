CREATE SCHEMA IF NOT EXISTS {schema};

DO $setup$
BEGIN
    CREATE TYPE {schema}.dataset_kind AS ENUM ('reviews', 'comments', 'messages');
EXCEPTION WHEN duplicate_object THEN
    NULL;
END
$setup$;

CREATE TABLE IF NOT EXISTS {schema}.datasets (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(100) NOT NULL UNIQUE CHECK (char_length(trim(name)) >= 3),
    kind {schema}.dataset_kind NOT NULL,
    labels text[] NOT NULL CHECK (cardinality(labels) > 0),
    is_public boolean NOT NULL DEFAULT false
);

CREATE TABLE IF NOT EXISTS {schema}.models (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(100) NOT NULL UNIQUE CHECK (char_length(trim(name)) >= 3),
    is_active boolean NOT NULL DEFAULT true
);

CREATE TABLE IF NOT EXISTS {schema}.experiments (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title varchar(150) NOT NULL CHECK (char_length(trim(title)) >= 3),
    dataset_id integer NOT NULL,
    model_id integer NOT NULL,
    run_date date NOT NULL,
    created_at timestamptz NOT NULL DEFAULT current_timestamp,
    f1 numeric(5,4) NOT NULL CONSTRAINT experiments_f1_check CHECK (f1 BETWEEN 0 AND 1),
    samples integer NOT NULL CHECK (samples > 0),
    notes text,
    UNIQUE (title, dataset_id, model_id, run_date),
    CONSTRAINT experiments_dataset_fk FOREIGN KEY (dataset_id) REFERENCES {schema}.datasets(id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT experiments_model_fk FOREIGN KEY (model_id) REFERENCES {schema}.models(id)
        ON UPDATE CASCADE ON DELETE CASCADE
);
